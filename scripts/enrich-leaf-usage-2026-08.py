    leaf_ids = {c["id"] for c in cats if c.get("kind") == "leaf"}
    missing = leaf_ids - USAGE.keys()
    extra = USAGE.keys() - leaf_ids
    if missing:
        raise SystemExit(f"USAGE missing: {sorted(missing)}")
    if extra:
        raise SystemExit(f"USAGE unknown: {sorted(extra)}")
    n = 0
    for c in cats:
        if c.get("kind") != "leaf":
            continue
        text = USAGE[c["id"]]
        if c.get("usageMd") != text:
            c["usageMd"] = text
            n += 1
    CAT_PATH.write_text(json.dumps(cats, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"updated usageMd on {n} leaves ({len(leaf_ids)} total)")


